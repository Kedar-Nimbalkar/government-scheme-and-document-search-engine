BEGIN;

CREATE TABLE department (
    dept_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dept_name text NOT NULL,
    level text NOT NULL CHECK (level IN ('Central', 'State')),
    UNIQUE (dept_name, level)
);

CREATE TABLE scheme (
    scheme_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dept_id integer NOT NULL REFERENCES department,
    scheme_name text NOT NULL,
    category text NOT NULL,
    state text NOT NULL
);
CREATE INDEX scheme_filter_idx ON scheme (state, dept_id, category);
CREATE INDEX scheme_department_idx ON scheme (dept_id);
CREATE INDEX scheme_category_idx ON scheme (category);

CREATE TABLE app_user (
    user_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dept_id integer REFERENCES department,
    username text NOT NULL UNIQUE,
    password_hash text NOT NULL,
    role text NOT NULL CHECK (role IN ('admin', 'department', 'citizen')),
    CHECK (role <> 'department' OR dept_id IS NOT NULL)
);

CREATE TABLE document (
    doc_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scheme_id integer NOT NULL REFERENCES scheme,
    uploaded_by integer REFERENCES app_user,
    title text NOT NULL,
    circular_no text,
    issue_date date,
    file_path text UNIQUE,
    status text NOT NULL DEFAULT 'Active' CHECK (status IN ('Active', 'Superseded')),
    superseded_by integer REFERENCES document,
    CHECK (superseded_by <> doc_id)
);
CREATE INDEX document_scheme_idx ON document (scheme_id);

CREATE TABLE bookmark (
    bookmark_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id integer NOT NULL REFERENCES app_user,
    doc_id integer NOT NULL REFERENCES document,
    page_no integer CHECK (page_no > 0),
    created_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE NULLS NOT DISTINCT (user_id, doc_id, page_no)
);

CREATE TABLE operational_log (
    log_id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    user_id integer REFERENCES app_user,
    doc_id integer REFERENCES document,
    event text NOT NULL,
    details jsonb NOT NULL DEFAULT '{}',
    logged_at timestamptz NOT NULL DEFAULT now()
);

COMMIT;
